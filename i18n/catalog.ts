export const CATALOGS: Record<Lang, Messages> = { en, ja };

/** The text for one key. Unknown keys fall back to English, then to the key. */
export function t(lang: Lang, key: MessageKey, params?: Record<string, string | number>): string {
  const catalog = CATALOGS[lang] ?? en;
  const template = catalog[key] ?? en[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.hasOwn(params, name) ? String(params[name]) : match,
  );
}

/** The same, for values that may be a language string from the outside. */
export function text(
  lang: string | null | undefined,
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  return t(lang === 'ja' ? 'ja' : 'en', key, params);
}
